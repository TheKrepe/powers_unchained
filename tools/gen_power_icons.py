def main():
    os.makedirs(OUT, exist_ok=True)
    for name, (grid, colours) in ICONS.items():
        rows = [r for r in grid.strip('\n').split('\n')]
        img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch in colours:
                    img.putpixel((x, y), colours[ch] + (255,))
        # 1px dark outline so the icons read on the blue and the grey segment
        out = img.copy()
        for y in range(16):
            for x in range(16):
                if img.getpixel((x, y))[3] == 0 and any(
                        0 <= x + dx < 16 and 0 <= y + dy < 16 and img.getpixel((x + dx, y + dy))[3] > 0
                        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    out.putpixel((x, y), (16, 22, 30, 150))
        out.save(os.path.join(OUT, name + '.png'))


if __name__ == '__main__':
    main()
